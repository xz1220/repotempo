const (
	localeEnglish    = "en"
	localeChinese    = "zh-CN"
	localeCookieName = "github_radar_locale"
)

type localizer struct {
	locale string
}

func newLocalizer(locale string) localizer {
	return localizer{locale: normalizeLocale(locale)}
}

func normalizeLocale(locale string) string {
	switch strings.ToLower(strings.ReplaceAll(strings.TrimSpace(locale), "_", "-")) {
	case "zh", "zh-cn", "zh-hans", "zh-hans-cn":
		return localeChinese
	case "en", "en-us", "en-gb":
		return localeEnglish
	default:
		return localeEnglish
	}
}

func requestedLocale(locale string) (string, bool) {
	if strings.TrimSpace(locale) == "" {
		return "", false
	}
	normalized := normalizeLocale(locale)
	switch strings.ToLower(strings.ReplaceAll(strings.TrimSpace(locale), "_", "-")) {
	case "zh", "zh-cn", "zh-hans", "zh-hans-cn", "en", "en-us", "en-gb":
		return normalized, true
	default:
		return "", false
	}
}

func (l localizer) Text(key string) string {
	if messages, ok := messageCatalog[l.locale]; ok {
		if value, ok := messages[key]; ok {
			return value
		}
	}
	if value, ok := messageCatalog[localeEnglish][key]; ok {
		return value
	}
	return key
}

func (l localizer) Textf(key string, values ...any) string {
	return fmt.Sprintf(l.Text(key), values...)
}

func (l localizer) StatusLabel(value string) string {
	key := "status." + strings.ToLower(value)
	if value == "" {
		key = "status.unknown"
	}
	translated := l.Text(key)
	if translated == key {
		return value
	}
	return translated
}

func (l localizer) SourceLabel(value string) string {
	key := "source." + strings.ToLower(value)
	if value == "" {
		key = "source.unknown"
	}
	translated := l.Text(key)
	if translated == key {
		return value
	}
	return translated
}

func (l localizer) TopicName(slug, fallback string) string {
	key := "category." + slug
	if value := l.Text(key); value != key {
		return value
	}
	return fallback
}

func (l localizer) WarningText(value string) string {
	if value == "Current snapshot coverage is temporarily unavailable." {
		return l.Text("warning.coverage_unavailable")
	}
	return value
}

